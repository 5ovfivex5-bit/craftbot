#!/usr/bin/env python3
"""Generate dashboard/src/gen_palette.h from the simulator registry (PROTOCOL.md 12.2).

Input : data/registry/blocks.json (block name, id, color [r,g,b], pseudo flag)
        data/registry/mobs.json   (mob name, pseudo_block_id, size [w,h], hostile)
Output: dashboard/src/gen_palette.h (rewritten only when the text changes)

Run: python3 -I dashboard/tools/gen_palette.py
The ids are the file order and must be dense (id == index). Nothing here assumes a fixed count:
the header carries kBlockCount / kMobCount, and the dashboard reads them.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DASH = os.path.dirname(HERE)
ROOT = os.path.dirname(DASH)
BLOCKS = os.path.join(ROOT, "data", "registry", "blocks.json")
MOBS = os.path.join(ROOT, "data", "registry", "mobs.json")
OUT = os.path.join(DASH, "src", "gen_palette.h")

# Speckle colours for ore / chest blocks (mirrors the v6 dashboard palette; cosmetic only).
SPECKLE = {
    "coal_ore": (25, 25, 25), "deepslate_coal_ore": (25, 25, 25),
    "iron_ore": (216, 175, 147), "deepslate_iron_ore": (216, 175, 147),
    "diamond_ore": (90, 230, 230), "deepslate_diamond_ore": (90, 230, 230),
    "gold_ore": (252, 238, 77), "deepslate_gold_ore": (252, 238, 77),
    "nether_quartz_ore": (235, 229, 222),
    "chest": (80, 50, 25),
}


def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def rgb(c, what):
    if not (isinstance(c, list) and len(c) == 3 and all(isinstance(v, int) and 0 <= v <= 255 for v in c)):
        sys.exit(f"{what}: color must be [r,g,b] with 0..255, got {c!r}")
    return c


def render(blocks, mobs):
    lines = []
    w = lines.append
    w("// GENERATED by dashboard/tools/gen_palette.py from data/registry/blocks.json and mobs.json.")
    w("// Do not edit by hand; rerun the script after the registry changes.")
    w("#pragma once")
    w("")
    w("#include <cstdint>")
    w("")
    w("namespace mm::gen {")
    w("")
    w(f"constexpr int kBlockCount = {len(blocks)};")
    w(f"constexpr int kMobCount = {len(mobs)};")
    w("")
    w("struct GenBlock {")
    w("    const char* name;")
    w("    uint8_t rgb[3];")
    w("    uint8_t speckle[3];")
    w("    bool has_speckle;")
    w("    bool pseudo;  // agent and mob ids: never world voxels")
    w("};")
    w("")
    w("struct GenMob {")
    w("    const char* name;")
    w("    int pseudo_id;  // block id of the mob's pseudo-block")
    w("    float width, height;")
    w("    bool hostile;")
    w("};")
    w("")
    w("// Index == block id.")
    w("inline constexpr GenBlock kBlocks[kBlockCount] = {")
    for i, b in enumerate(blocks):
        name = b["name"]
        c = rgb(b.get("color", [128, 128, 128]), f"block {name}")
        sp = SPECKLE.get(name)
        s = sp or (0, 0, 0)
        w(f'    {{"{name}", {{{c[0]}, {c[1]}, {c[2]}}}, {{{s[0]}, {s[1]}, {s[2]}}}, {"true" if sp else "false"}, '
          f'{"true" if b.get("pseudo") else "false"}}},  // {i}')
    w("};")
    w("")
    w("inline constexpr GenMob kMobs[kMobCount] = {")
    for m in mobs:
        size = m.get("size", [0.6, 1.8])
        w(f'    {{"{m["name"]}", {int(m["pseudo_block_id"])}, {float(size[0])}f, {float(size[1])}f, '
          f'{"true" if m.get("hostile") else "false"}}},')
    w("};")
    w("")
    w("}  // namespace mm::gen")
    w("")
    return "\n".join(lines)


def main():
    blocks = load(BLOCKS)
    mobs = load(MOBS)
    for i, b in enumerate(blocks):
        if b.get("id") != i:
            sys.exit(f"blocks.json: ids must be dense, entry {i} has id {b.get('id')}")
    names = {b["name"]: b["id"] for b in blocks}
    for m in mobs:
        pid = m.get("pseudo_block_id")
        if pid not in names.values() or blocks[pid]["name"] != m["name"]:
            sys.exit(f"mob {m['name']}: pseudo_block_id {pid} does not name a pseudo block of the same name")
    text = render(blocks, mobs)
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else None
    if old != text:
        with open(OUT, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"wrote {OUT} ({len(blocks)} blocks, {len(mobs)} mobs)")
    else:
        print(f"{OUT} unchanged")


if __name__ == "__main__":
    main()
