#!/usr/bin/env python3
"""Generate src/gen/blueprints.h from data/builds/blueprints.json (PROTOCOL 12.6, SIM-4 build runtime).

Inputs: data/builds/blueprints.json, data/registry/blocks.json (else blocks.seed.json),
data/registry/items.json (else items.seed.json). Output: src/gen/blueprints.h, rewritten only when the text
changes. Blueprint index = position in blueprints.json (= the index used by build_complete predicates in
src/gen/registry.h, see tools/gen_registry.py).

Each cell: x, y, z (blueprint-local, x = column, y = layer, z = row), block (world block id to place, or 0 for
a required-air cell), item (item index of the wanted item, 255 for required air). Solid cells are all non-'.'
cells. Required-air cells are the '.' cells enclosed by solid blocks on both sides of some axis inside the box
(room interiors, portal hole); they must stay air.

Run: python3 -I tools/gen_blueprints.py      (also callable from tests/test_build.py)
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "gen", "blueprints.h")
FAMILIES = ["shelter", "house", "tower", "bridge", "wall", "portal", "farm", "decor"]


def load_names(stem):
    for name in (stem + ".json", stem + ".seed.json"):
        path = os.path.join(ROOT, "data", "registry", name)
        if os.path.exists(path):
            with open(path) as f:
                data = json.load(f)
            return data if isinstance(data, list) else data[stem]
    raise SystemExit(f"missing data/registry/{stem}.json")


def fail(msg):
    print("gen_blueprints: " + msg, file=sys.stderr)
    raise SystemExit(1)


def cells_of(bp, block_of, item_of):
    sx, sy, sz = bp["size"]
    grid = [[[None] * sx for _ in range(sz)] for _ in range(sy)]
    for y, layer in enumerate(bp["layers"]):
        for z, row in enumerate(layer):
            for x, ch in enumerate(row):
                if ch != ".":
                    name = bp["palette"][ch]
                    grid[y][z][x] = (block_of(name), item_of(name))

    def solid(x, y, z):
        return 0 <= x < sx and 0 <= y < sy and 0 <= z < sz and grid[y][z][x] is not None

    out = []
    for y in range(sy):
        for z in range(sz):
            for x in range(sx):
                if grid[y][z][x] is not None:
                    b, i = grid[y][z][x]
                    out.append((x, y, z, b, i))
                    continue
                enclosed = False
                for axis in ((1, 0, 0), (0, 1, 0), (0, 0, 1)):
                    lo = hi = False
                    k = 1
                    while not lo:
                        if not (0 <= x - axis[0] * k < sx and 0 <= y - axis[1] * k < sy and 0 <= z - axis[2] * k < sz):
                            break
                        lo = solid(x - axis[0] * k, y - axis[1] * k, z - axis[2] * k)
                        if lo:
                            break
                        k += 1
                    k = 1
                    while not hi:
                        if not (0 <= x + axis[0] * k < sx and 0 <= y + axis[1] * k < sy and 0 <= z + axis[2] * k < sz):
                            break
                        hi = solid(x + axis[0] * k, y + axis[1] * k, z + axis[2] * k)
                        if hi:
                            break
                        k += 1
                    if lo and hi:
                        enclosed = True
                        break
                if enclosed:
                    out.append((x, y, z, 0, 255))
    return out


def main():
    with open(os.path.join(ROOT, "data", "builds", "blueprints.json")) as f:
        bps = json.load(f)
    blocks = {b["name"]: b["id"] for b in load_names("blocks")}
    items = {it["name"]: it["id"] for it in load_names("items")}

    def block_of(name):
        if name not in blocks:
            fail(f"palette item {name} has no block of that name")
        return blocks[name]

    def item_of(name):
        if name not in items:
            fail(f"palette item {name} is not in items.json")
        return items[name]

    lines = [
        "// GENERATED by tools/gen_blueprints.py from data/builds/blueprints.json and data/registry. Do not edit.",
        "// Blueprint index = position in blueprints.json. Cells: x, y, z (local), block (0 = required air), item.",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace craftsim::bp {",
        "",
        f"constexpr int NUM_BLUEPRINTS = {len(bps)};",
        "// family: index into {" + ", ".join(FAMILIES) + "}",
        "struct Cell { uint8_t x, y, z, block, item; };",
        "struct Blueprint {",
        "    const char* name;",
        "    uint8_t family, tier, vanilla;   // vanilla = 1 for converted vanilla structures",
        "    uint8_t sx, sy, sz;",
        "    uint16_t first, count;            // range in CELLS",
        "    uint16_t solid;                   // cells with block != 0",
        "};",
        "",
        "inline constexpr Cell CELLS[] = {",
    ]
    table = []
    cell_lines = []
    for idx, bp in enumerate(bps):
        if bp.get("id", idx) != idx:
            fail(f"blueprint {bp['name']} has id {bp['id']} at index {idx}")
        if bp["family"] not in FAMILIES:
            fail(f"unknown family {bp['family']}")
        cells = cells_of(bp, block_of, item_of)
        first = len(table)
        table.extend(cells)
        solid = sum(1 for c in cells if c[3] != 0)
        sx, sy, sz = bp["size"]
        vanilla = 1 if bp["source"].startswith("vanilla:") else 0
        table_meta = (bp["name"], FAMILIES.index(bp["family"]), bp["tier"], vanilla, sx, sy, sz, first,
                      len(cells), solid)
        cell_lines.append(table_meta)
    body = []
    row = []
    for c in table:
        row.append("{%d,%d,%d,%d,%d}" % c)
        if len(row) == 12:
            body.append("    " + ",".join(row) + ",")
            row = []
    if row:
        body.append("    " + ",".join(row) + ",")
    lines.extend(body)
    lines.append("};")
    lines.append("")
    lines.append("inline constexpr Blueprint BLUEPRINTS[NUM_BLUEPRINTS] = {")
    for m in cell_lines:
        name, fam, tier, van, sx, sy, sz, first, count, solid = m
        lines.append('    {"%s", %d, %d, %d, %d, %d, %d, %d, %d, %d},' % (name, fam, tier, van, sx, sy, sz, first,
                                                                          count, solid))
    lines.append("};")
    lines.append("")
    lines.append("}  // namespace craftsim::bp")
    lines.append("")
    text = "\n".join(lines)
    old = open(OUT).read() if os.path.exists(OUT) else None
    if old != text:
        os.makedirs(os.path.dirname(OUT), exist_ok=True)
        with open(OUT, "w") as f:
            f.write(text)
        print(f"gen_blueprints: wrote {OUT} ({len(bps)} blueprints, {len(table)} cells)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
